List<Doctor> filterDoctors({
  String? city,
  String? specialty,
  double? minRating,
  String? searchQuery,
}) {
  return mockDoctors.where((d) {
    if (city != null && city.isNotEmpty && d.city != city) return false;
    if (specialty != null && specialty.isNotEmpty && d.specialty != specialty) return false;
    if (minRating != null && d.rating < minRating) return false;
    if (searchQuery != null && searchQuery.isNotEmpty) {
      final q = searchQuery.toLowerCase();
      if (!d.name.toLowerCase().contains(q) &&
          !d.specialty.toLowerCase().contains(q) &&
          !d.hospital.toLowerCase().contains(q)) {
        return false;
      }
    }
    return true;
  }).toList();
}
